-- 附件存 JSON 而非单独建表：附件是消息的附属属性（一条消息最多挂一份合同），
-- 没有独立查询需求——没有人会问"这个文件被哪几条消息引用过"，而建关联表会让
-- "取一页消息"变成 N+1 次查询。这条判断与 0004 的 citations 完全同形。
--
-- 背景：用户上传合同后问"这份合同有什么风险"，答案里那轮对话刷新一次就只剩文字，
-- 合同卡片消失，点不回审查页。答辩演示"关掉页面再打开"时无法解释。
--
-- NULL 表示这条消息没有附件（assistant 消息恒为 NULL）：用 NULL 而不是空数组 '[]'，
-- 是为了让 SUM(attachments IS NULL) 能直接答"有多少条消息带附件"，
-- 也让迁移前的老数据天然落在"没有附件"这个正确语义上，不需要回填。
ALTER TABLE messages
  ADD COLUMN attachments MEDIUMTEXT NULL
    COMMENT '附件 JSON 数组（合同文件卡片），仅 user 消息，无附件时为 NULL';
