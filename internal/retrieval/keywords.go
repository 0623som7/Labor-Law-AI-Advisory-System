// Package retrieval 把用户的口语问题变成法条库能命中的检索。
//
// 为什么不能拿整句用户输入直接 LIKE：用户问的是"我被老板辞退了还没结工资怎么办"，
// 而库里写的是"用人单位解除劳动合同"、"劳动报酬"。整句匹配命中率接近零，
// 命中不了模型就会按提示词回答"需要核对原文"，产品看起来就是不会答。
//
// 这里用词表归一而不是分词库：劳动法领域的实体词是有限集合，两百个词覆盖绝大多数提问；
// 引入分词依赖会多一个必须随版本升级的第三方库，而它的收益在这个词表量级上看不出来。
package retrieval

import (
	"sort"
	"strings"
)

// aliases 把口语说法归一到法条用语，一个口语词可以对应多个检索词。
//
// 键是用户可能说的词，值是检索时真正拿去匹配的词。
// 归一的方向必须是"口语 → 法条用语"，反过来会搜不到：
// 条文里写"经济补偿"，几乎不会写"N+1"。
//
// 一对多是拿真实法条原文校准出来的，不是预防性设计：
//   - 用户说"加班费"，而《劳动法》第四十四条通篇只有"延长工作时间"，没有"加班"二字；
//   - 用户说"双倍工资"，而《劳动合同法》第八十二条写的是"每月支付二倍的工资"，
//     "二倍工资"这个连续词在整部法律里一次都没出现过。
