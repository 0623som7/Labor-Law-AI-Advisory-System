DIGITS = "零一二三四五六七八九"


def cn(n):
    """1..99 的中文数字，够用到"第九十九条"。"""
    if n < 10:
        return DIGITS[n]
    if n == 10:
        return "十"
    if n < 20:
        return "十" + DIGITS[n % 10]
    tens, ones = divmod(n, 10)
    return DIGITS[tens] + "十" + (DIGITS[ones] if ones else "")


HEAD = """<!doctype html>
<html lang="zh-CN"><head><meta charset="utf-8">
<title>%s</title>
<style>
  @page { size: A4; margin: 20mm 18mm; }
  body { font-family: "SimSun", "Songti SC", serif; font-size: 11pt; line-height: 1.9; color: #111; }
  h1 { font-size: 16pt; text-align: center; margin: 0 0 6pt; letter-spacing: 2pt; }
  .sub { text-align: center; font-size: 9.5pt; color: #444; margin-bottom: 14pt; }
  .party { margin: 0 0 4pt; }
  p.cl { margin: 0 0 7pt; text-align: justify; }
  .page { page-break-after: always; }
  .page:last-of-type { page-break-after: auto; }
  .sign { margin-top: 18pt; }
  .sign p { margin: 0 0 6pt; }
</style></head><body>
"""

TAIL = "</body></html>\n"


def render(title, sub, head_blocks, pages, sign):
    """pages 是 [[条款文本, ...], ...]，每层一个物理页；条款号全局连续。"""
    out = [HEAD % title, "<h1>%s</h1>\n" % title, '<div class="sub">%s</div>\n' % sub]
    no = 0
    total = len(pages)
    for idx, page in enumerate(pages):
        out.append('<section class="page">\n')
        if idx == 0:
            for block in head_blocks:
                out.append(block)
        for text in page:
            no += 1
            out.append('<p class="cl">第%s条 %s</p>\n' % (cn(no), text))
        if idx == total - 1:
            out.append(sign)
        out.append("</section>\n")
    out.append(TAIL)
    return "".join(out)


